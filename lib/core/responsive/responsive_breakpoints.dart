class ResponsiveBreakpoints {
  // This breakpoint is used for compact mobile layouts.
  static const double mobile = 600;

  // This breakpoint is used for medium tablet layouts.
  static const double tablet = 1024;

  // This breakpoint is used for desktop and web layouts.
  static const double desktop = 1280;

  // This breakpoint is used for very wide desktop layouts.
  static const double wideDesktop = 1440;

  // This max content width is used to avoid stretched UI on web.
  static const double maxContentWidth = 1280;

  // This max form width is used for auth and form-heavy pages on web.
  static const double maxFormWidth = 760;

  // This max narrow content width is used for detail pages and compact content.
  static const double maxNarrowContentWidth = 920;

  // This sidebar width is used for desktop portal navigation.
  static const double sidebarWidth = 288;
}